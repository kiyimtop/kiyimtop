-- KiyimTop: удалить ВСЕ тестовые магазины, их товары и размеры (запустить перед запуском для покупателей).
-- Удаляются только записи, у которых номер (id) начинается с d0000000-0000-4000-8000-.
-- Товары и размеры тестовых магазинов удаляются вместе с магазинами автоматически.
--
-- Как запустить: Supabase → SQL Editor → New query → вставить весь файл → Run.

begin;

delete from public.shops
where id::text like 'd0000000-0000-4000-8000-%';

commit;
